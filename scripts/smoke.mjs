import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { launchBrowser, contextOptions } from '../browser.mjs';

process.env.PORT = '3068';
process.env.POC_DATA_DIR = '.poc/smoke';
const { server, sessions, shutdown } = await import('../server.mjs');
if (!server.listening) await new Promise(resolve => server.once('listening', resolve));
await mkdir('.poc', { recursive: true });
const viewerBrowser = await launchBrowser();
const viewerContext = await viewerBrowser.newContext({ ...contextOptions, viewport: { width: 1440, height: 1100 } });
const viewer = await viewerContext.newPage();
const errors = [];
viewer.on('pageerror', error => errors.push(error.message));
try {
  await viewer.goto('http://localhost:3068');
  await viewer.getByRole('button', { name: 'Start your pipeline' }).waitFor();
  await viewer.screenshot({ path: '.poc/desktop-empty.png', fullPage: true });
  await viewer.getByRole('button', { name: 'Start your pipeline' }).click();
  await viewer.waitForFunction(() => Number(document.querySelector('#screen').dataset.frames) > 2, { timeout: 45000 });
  const id = (await viewerContext.cookies()).find(cookie => cookie.name === 'dp67').value;
  const session = sessions.get(id);
  const krillion = session.pages.get('krillion');
  await krillion.getByRole('button', { name: /BEGIN DESCENT/ }).waitFor({ timeout: 30000 });
  await viewer.waitForTimeout(2000);
  await viewer.screenshot({ path: '.poc/desktop-krillion.png', fullPage: true });
  const remoteBox = await krillion.getByRole('button', { name: /BEGIN DESCENT/ }).boundingBox();
  const canvasBox = await viewer.locator('#screen').boundingBox();
  await viewer.mouse.click(canvasBox.x + (remoteBox.x + remoteBox.width / 2) * canvasBox.width / session.viewport.width, canvasBox.y + (remoteBox.y + remoteBox.height / 2) * canvasBox.height / session.viewport.height);
  await krillion.locator('input').first().waitFor({ state: 'visible', timeout: 15000 });
  await viewer.keyboard.type('test');
  await krillion.waitForFunction(() => [...document.querySelectorAll('input')].some(input => input.value === 'test'));
  console.log('PASS Krillion: stream, click-through and keyboard entry');
  await viewer.getByRole('button', { name: /02 Maptap/ }).click();
  await viewer.waitForFunction(() => document.querySelector('#status').textContent === 'Maptap is live');
  const maptap = session.pages.get('maptap');
  await maptap.waitForTimeout(8000);
  const before = await maptap.evaluate(() => myGlobe.pointOfView());
  const box = await viewer.locator('#screen').boundingBox();
  await viewer.mouse.move(box.x + box.width * .35, box.y + box.height * .65);
  await viewer.mouse.down();
  await viewer.mouse.move(box.x + box.width * .55, box.y + box.height * .65, { steps: 16 });
  await viewer.mouse.up();
  await viewer.waitForTimeout(2500);
  const after = await maptap.evaluate(() => myGlobe.pointOfView());
  assert(Math.abs(before.lng - after.lng) > 5, 'Maptap longitude should change after dragging');
  console.log('PASS Maptap: stream and globe drag');
  await viewer.screenshot({ path: '.poc/desktop-maptap.png', fullPage: true });
  await writeFile('.poc/maptap-live-dom.html', await maptap.content());
  await viewer.setViewportSize({ width: 390, height: 844 });
  await viewer.getByRole('button', { name: /02 Maptap/ }).click();
  await viewer.waitForFunction(() => document.querySelector('#status').textContent === 'Maptap is live');
  await viewer.waitForTimeout(1500);
  await viewer.screenshot({ path: '.poc/mobile-maptap.png', fullPage: true });
  assert(await viewer.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile layout must not overflow');
  assert.deepEqual(errors, [], 'No frontend page errors');
  console.log('METRICS:', JSON.stringify({ frames: session.frames, megabytes: session.bytes / 1e6, seconds: (Date.now() - session.createdAt) / 1000 }));
} finally {
  await viewerBrowser.close();
  await shutdown();
}
